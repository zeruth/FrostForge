namespace {

uint32_t Word(uint32_t offset) {
    uint32_t word;
    std::memcpy(&word, g_rndSeedTable + offset, sizeof(word));
    return word;
}

uint32_t Rotl(uint32_t value, int32_t bits) {
    return (value << bits) | (value >> (32 - bits));
}

}  // namespace

// ref: FUN_14133cae0
void RndSeedInit(CRndSeed* seed, uint32_t value) {
    seed->m_sum = value;
    seed->m_cursors = (value % 0x3b) * 0x400 | (value % 0x3d) * 4 | (value % 0x35) * 0x40000
        | ((value / 0x2f) * 0x11 + value) * 0x4000000;
}

// ref: FUN_1403068a0
uint32_t RndSeedNext(CRndSeed* seed) {
    uint32_t cursors = seed->m_cursors;
    uint32_t b3 = cursors >> 24;
    uint32_t b2 = (cursors >> 16) & 0xff;
    uint32_t b1 = (cursors >> 8) & 0xff;
    uint32_t b0 = cursors & 0xff;
    uint32_t i3 = 3 < b3 ? b3 - 4 : b3 + 0xb8;
    uint32_t i2 = 0xb < b2 ? b2 - 0xc : b2 + 200;
    uint32_t i1 = 0x17 < b1 ? b1 - 0x18 : b1 + 0xd4;
    uint32_t i0 = 0x1b < b0 ? b0 - 0x1c : b0 + 0xd8;
    uint32_t sum = (Rotl(Word(i1), 3) ^ Rotl(Word(i2), 2) ^ Rotl(Word(i3), 1) ^ Word(i0)) + seed->m_sum;
    seed->m_cursors = ((i3 << 8 | i2) << 8 | i1) << 8 | i0;
    seed->m_sum = sum;
    return sum;
}

float RndSeedMantissa(uint32_t sum) {
    uint32_t bits = (sum & 0x7fffff) | 0x3f800000;
    float value;
    std::memcpy(&value, &bits, sizeof(value));
    return value;
}

float RndSeedUnit(CRndSeed* seed) {
    return RndSeedMantissa(RndSeedNext(seed)) - 1.0f;
}

float RndSeedSigned(CRndSeed* seed) {
    uint32_t sum = RndSeedNext(seed);
    float value = RndSeedMantissa(sum);
    if (static_cast<int32_t>(sum) < 0) {
        return 2.0f - value;
    }
    return value - 2.0f;
}
