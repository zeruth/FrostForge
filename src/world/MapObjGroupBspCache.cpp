#include "ui/FrameTime.hpp"
#include "world/WorldQueries.hpp"
#include <cstdint>

namespace {

struct BSPCACHE {
    uint32_t m_used[0x400];         // 0x0000
    uint32_t m_group[0x400];        // 0x1000
    uint16_t m_key[0x400];          // 0x2000
    uint8_t m_results[0xa03800 - 0x2800];  // 0x2800, 0x2804 a way
};
static_assert(sizeof(BSPCACHE) == 0xa03800, "BSPCACHE is 0xa03800 bytes");

BSPCACHE* s_bspCaches[3];           // DAT_1430ac0e0
uint32_t s_bspCacheTime;            // DAT_1430ac0d8: the frame time last seen

}  // namespace

// Once a frame: when the frame time went back (a new session of time), every cache forgets.
// ref: FUN_14139abd0
void BspCacheUpdate() {
    uint32_t now = FrameTime_GetTime();
    if (now < s_bspCacheTime) {
        for (BSPCACHE* cache : s_bspCaches) {
            if (cache == nullptr) {
                continue;
            }
            for (int32_t i = 0; i < 0x400; i++) {
                cache->m_used[i] = 0;
                cache->m_group[i] = 0;
                cache->m_key[i] = 0xffff;
            }
        }
    }
    s_bspCacheTime = now;
}

