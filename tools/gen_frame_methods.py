"""A frame type's Lua methods, forwarded to the reference's own, translated.

A script-object class registers a table of {name, lua_CFunction} pairs (FrameScript_Object::
FillScriptMethodTable). This reads that table out of the reference image and writes the port's
side: one forwarder per method, each `// translated: FUN_x` (so tools/translate.py takes it as a
root) and guarded by GenFault, and the class's FillScriptMethods in the port's own pattern.

    python tools/gen_frame_methods.py <Class> <table hex> <count> <base fill function> <out.cpp>
                                      [--include header]...

The methods run on the port's object. They read it at the reference's offsets, so the class
keeps the reference's layout past its base (see the class's header).
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

from wowbin import Binary

ROOT = Path(__file__).resolve().parent.parent


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cls")
    ap.add_argument("table")
    ap.add_argument("count", type=lambda s: int(s, 0))
    ap.add_argument("base_fill")
    ap.add_argument("out")
    ap.add_argument("--include", action="append", default=[])
    args = ap.parse_args()

    b = Binary()
    table = int(args.table, 16)
    methods = []
    for k in range(args.count):
        name = b.cstr(b.u64(table + 16 * k))
        fn = b.u64(table + 16 * k + 8)
        methods.append((name, fn))

    out = [f"// GENERATED by tools/gen_frame_methods.py from the reference's table at 0x{table:x}; do not",
           "// edit by hand. Each method is the reference's own, translated (src/gen), run under GenFault.",
           ""]
    out += [f'#include "{h}"' for h in args.include]
    out += ['#include "framescript/FrameScriptObject.hpp"', "", "#include <windows.h>", "",
            'extern "C" {', "struct lua_State;",
            "int GenFault(unsigned long long address, EXCEPTION_POINTERS* info);"]
    for fn in sorted({fn for _, fn in methods}):
        out.append(f"unsigned long long FUN_{fn:x}(unsigned long long L);")
    out += ["}", "", "namespace {", ""]
    seen = set()
    for name, fn in methods:
        if fn in seen:
            continue
        seen.add(fn)
        out += [f"// translated: FUN_{fn:x}",
                f"int Method_{fn:x}(lua_State* L) {{",
                "    __try {",
                f"        return static_cast<int>(FUN_{fn:x}(reinterpret_cast<unsigned long long>(L)));",
                f"    }} __except (GenFault(0x{fn:x}ull, GetExceptionInformation())) {{",
                "        return 0;",
                "    }",
                "}", ""]
    out += ["struct METHOD {", "    const char* m_name;", "    int (*m_function)(lua_State*);", "};", "",
            f"const METHOD s_methods[] = {{"]
    out += [f'    {{ "{name}", Method_{fn:x} }},' for name, fn in methods]
    out += ["};", "", "}  // namespace", "",
            f"void {args.base_fill}(lua_State* L);", "",
            f"// The reference's table at 0x{table:x} ({args.count} methods), after the base class's.",
            f"void {args.cls}_FillScriptMethods(lua_State* L) {{",
            f"    {args.base_fill}(L);",
            f"    FrameScript_Object::FillScriptMethodTable(L, s_methods, {args.count});",
            "}", ""]
    path = ROOT / args.out
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{path.relative_to(ROOT)}: {args.count} methods, {len(seen)} functions")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
