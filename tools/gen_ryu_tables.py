"""Emit src/storm/string/RyuTables.hpp from the reference binary.

Storm's float formatting (0x14025e2c0 -> 0x1402681c0 -> 0x140267a90) is Ryu's d2d. Its
tables are read out of the binary rather than taken from Ryu's source, so they are exactly
what the reference uses:
  0x142621090  DOUBLE_POW5_INV_SPLIT  (292 x 128-bit, low/high qwords)
  0x1426222d0  DOUBLE_POW5_SPLIT      (326 x 128-bit)
  0x142623728  powers of ten, read from index -1 by the rounding code (0x142623728 + 8*n)

    python tools/gen_ryu_tables.py
"""
import struct
from pathlib import Path

from wowbin import ROOT, Binary

INV, POW5, POW10 = 0x142621090, 0x1426222D0, 0x142623730


def main() -> None:
    b = Binary()
    inv = [(b.u64(INV + 16 * i), b.u64(INV + 16 * i + 8)) for i in range((POW5 - INV) // 16)]
    pow5 = [(b.u64(POW5 + 16 * i), b.u64(POW5 + 16 * i + 8)) for i in range((POW10 - POW5) // 16)]
    # the powers-of-ten table and the table after it, read as one run of qwords
    pow10 = [b.u64(POW10 + 8 * i) for i in range(40)]

    nl = chr(10)
    out = [
        "#ifndef STORM_STRING_RYU_TABLES_HPP",
        "#define STORM_STRING_RYU_TABLES_HPP",
        "",
        "// Generated by tools/gen_ryu_tables.py from WowClassic-clean.exe. Do not edit.",
        "",
        "#include <cstdint>",
        "",
        f"// DAT_142621090: {len(inv)} entries (low, high)",
        f"static const uint64_t s_ryuPow5InvSplit[{len(inv)}][2] = {{",
    ]
    out += [f"    {{ 0x{lo:016X}ull, 0x{hi:016X}ull }}," for lo, hi in inv]
    out += ["};", "", f"// DAT_1426222d0: {len(pow5)} entries (low, high)",
            f"static const uint64_t s_ryuPow5Split[{len(pow5)}][2] = {{"]
    out += [f"    {{ 0x{lo:016X}ull, 0x{hi:016X}ull }}," for lo, hi in pow5]
    out += ["};", "", "// DAT_142623730: the qwords from here on, as the reference reads them",
            f"static const uint64_t s_pow10Run[{len(pow10)}] = {{"]
    out += [f"    0x{v:016X}ull,  // [{i}] {v}" for i, v in enumerate(pow10)]
    out += ["};", "", "#endif", ""]

    path = ROOT / "src" / "storm" / "string" / "RyuTables.hpp"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(nl.join(out), encoding="utf-8")
    print(f"wrote {path}: inv {len(inv)}, pow5 {len(pow5)}")
    print("pow10 run:", pow10[:24])


if __name__ == "__main__":
    main()
