"""FrostForge's opcode table and its handlers against the client's (docs/opcodes.json, read out of
the 3.4.3.54261 binary by tools/opcodes.py: the client is the source of truth).

    python tools/opcode_diff.py [--server path/to/azerothcore-FrostForge]   # -> docs/opcode-diff.md

Reports, per direction:
  - numbers: an opcode name whose value differs between the two, and opcodes either side lacks
  - handlers: for client->server opcodes, whether the server handles them at all (the
    opcode table's handler), still marks them as "not converted to the 3.4.3 layout yet", or
    has no entry; for server->client opcodes, whether the server ever sends them
The layouts themselves (field by field) are the next step: the client's parsers and writers
name their stream calls in docs/opcodes.json ("reads", "writes").
"""
from __future__ import annotations

import argparse
import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SERVER = Path(r"C:\Users\tyler\Documents\code\azerothcore-FrostForge")


def server_enum(path: Path) -> dict[str, int]:
    text = path.read_text(encoding="utf-8", errors="replace")
    return {m.group(1): int(m.group(2), 16) for m in re.finditer(r"^\s*((?:CMSG|SMSG)_\w+)\s*=\s*0x([0-9A-Fa-f]+)", text, re.M)}


def server_handlers(src: Path) -> dict[str, str]:
    """Each CMSG's handler state from Opcodes.cpp's DEFINE_HANDLER / DEFINE_SERVER_OPCODE_HANDLER."""
    state: dict[str, str] = {}
    cpp = src / "src/server/game/Server/Protocol/Opcodes.cpp"
    text = cpp.read_text(encoding="utf-8", errors="replace") if cpp.exists() else ""
    for m in re.finditer(r"DEFINE_HANDLER\(\s*(CMSG_\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*,\s*&WorldSession::(\w+)", text):
        name, status, _, fn = m.groups()
        state[name] = "null" if fn in ("Handle_NULL", "Handle_EarlyProccess", "Handle_ServerSide", "Handle_Deprecated") \
            else ("unhandled" if status == "STATUS_UNHANDLED" else "handled")
    return state


def server_layouts(src: Path) -> dict[str, str]:
    """Each opcode's packet layout in the server's table: LAYOUT_343 (converted to the client's) or
    LAYOUT_335 (AC's own: never sent, ignored when received)."""
    cpp = src / "src/server/game/Server/Protocol/Opcodes.cpp"
    text = cpp.read_text(encoding="utf-8", errors="replace") if cpp.exists() else ""
    return {m.group(1): m.group(2) for m in re.finditer(r"DEFINE_\w*HANDLER\(\s*((?:CMSG|SMSG)_\w+)\b[^;]*?\b(LAYOUT_3[34]5|LAYOUT_343|LAYOUT_335)\s*\)", text)}


def server_sends(src: Path) -> Counter:
    """How often each SMSG name appears in the server's sources (a send, a packet class's opcode)."""
    c: Counter = Counter()
    for p in (src / "src/server").rglob("*.cpp"):
        if p.name in ("Opcodes.cpp",):
            continue
        for m in re.finditer(r"\bSMSG_\w+", p.read_text(encoding="utf-8", errors="replace")):
            c[m.group(0)] += 1
    for p in (src / "src/server").rglob("*.h"):
        if p.name == "Opcodes.h":
            continue
        for m in re.finditer(r"\bSMSG_\w+", p.read_text(encoding="utf-8", errors="replace")):
            c[m.group(0)] += 1
    return c


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--server", type=Path, default=DEFAULT_SERVER)
    args = ap.parse_args()
    client = json.loads((ROOT / "docs/opcodes.json").read_text(encoding="utf-8"))
    server = server_enum(args.server / "src/server/game/Server/Protocol/Opcodes.h")
    handlers = server_handlers(args.server)
    sends = server_sends(args.server)
    layouts = server_layouts(args.server)
    out = ["# FrostForge against the 3.4.3 client's opcodes", "",
           "Generated by `tools/opcode_diff.py` from `docs/opcodes.json` (the client) and the FrostForge sources.", ""]
    for direction in ("cmsg", "smsg"):
        recs = client[direction]
        by_value = {r["opcode"]: r for r in recs}
        client_names = {r["name"]: r["opcode"] for r in recs if r.get("name")}
        side = {n: v for n, v in server.items() if n.startswith(direction.upper())}
        mismatched = sorted((n, side[n], client_names[n]) for n in side if n in client_names and side[n] != client_names[n])
        server_only = sorted(n for n in side if side[n] not in by_value)
        client_only = sorted(v for v in by_value if v not in set(side.values()))
        out += [f"## {direction.upper()}", "",
                f"- client opcodes: {len(recs)}; server names: {len(side)}",
                f"- same name, different number: {len(mismatched)}",
                f"- server numbers the client does not have: {len(server_only)}",
                f"- client numbers the server does not name: {len(client_only)}", ""]
        converted = sorted(n for n in side if layouts.get(n) == "LAYOUT_343")
        pending = sorted(n for n in side if layouts.get(n) != "LAYOUT_343")
        out += [f"- converted to the 3.4.3 layout (LAYOUT_343): {len(converted)} of {len(side)}"
                f" ({100 * len(converted) / max(1, len(side)):.1f}%)", ""]
        for n, sv, cv in mismatched[:200]:
            out.append(f"  - `{n}` server 0x{sv:04X}, client 0x{cv:04X}")
        for n in server_only[:200]:
            out.append(f"  - server only: `{n}` 0x{side[n]:04X}")
        for v in client_only[:200]:
            out.append(f"  - client only: 0x{v:04X} {by_value[v].get('name') or ''}")
        # (the evidence-backed client names first: those are the opcodes a session uses)
        conf = {r["name"]: r.get("confidence", "") for r in recs if r.get("name")}
        out += [f"<details><summary>{len(pending)} not converted yet</summary>", ""]
        out += [f"- `{n}` ({conf.get(n, '')})" for n in sorted(pending, key=lambda n: (conf.get(n) != "evidence", n))]
        out += ["", "</details>", ""]
        if direction == "cmsg":
            states = Counter(handlers.get(n, "no entry") for n in side)
            out += ["", "Server handling of client opcodes: " + ", ".join(f"{k} {v}" for k, v in states.most_common()), ""]
            unhandled = sorted(n for n in side if handlers.get(n, "no entry") != "handled")
            out += [f"<details><summary>{len(unhandled)} not handled</summary>", ""] + [f"- `{n}`" for n in unhandled] + ["", "</details>", ""]
        else:
            never = sorted(n for n in side if sends[n] == 0)
            out += ["", f"Server->client opcodes the server never names outside the table: {len(never)} of {len(side)}", "",
                    f"<details><summary>never sent</summary>", ""] + [f"- `{n}`" for n in never] + ["", "</details>", ""]
    (ROOT / "docs/opcode-diff.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(l for l in out if l.startswith("- ") or l.startswith("Server")))


if __name__ == "__main__":
    main()
