"""Reads Gx's vertex formats out of the binary into src/gx/GxVertexFormats.inc.

    python tools/gen_vertex_formats.py

The 0x2b formats sit in .data at 0x142d41d78, 0xa0 bytes each: the attribute list, its count
and the stride; the rest of each entry (the attributes by semantic and the masks) is filled
in by CGxDevice's constructor (FUN_142290650). An attribute is 16 bytes: semantic (an index
into the names at 0x142913490), type (an index into the vertex formats at 0x142913520),
offset, stream.
"""
import struct

from wowbin import ROOT, Binary

TABLE = 0x142D41D78
COUNT = 0x2B
ENTRY = 0xA0


def main() -> None:
    b = Binary()
    lines = [
        "// Generated by tools/gen_vertex_formats.py from WowClassic-clean.exe: Gx's vertex formats",
        "// (0x142d41d78): {semantic, type, offset, stream} per attribute, then each format's",
        "// attribute list, count and stride.",
        "",
    ]
    formats = []
    for i in range(COUNT):
        entry = TABLE + i * ENTRY
        ptr = b.u64(entry)
        count = b.u32(entry + 8)
        stride = b.u32(entry + 12)
        name = "nullptr"
        if count:
            name = f"s_vertexAttribs{i}"
            lines.append(f"const GXVERTEXATTRIB {name}[{count}] = {{")
            for k in range(count):
                sem, typ, off, stream = struct.unpack_from("<IIII", b.image, b.off(ptr + k * 16))
                lines.append(f"    {{ {sem}, {typ}, {off}, {stream} }},")
            lines.append("};")
        formats.append((name, count, stride))
    lines.append("")
    lines.append(f"GXVERTEXFORMATDESC g_gxVertexFormats[{COUNT}] = {{")
    for name, count, stride in formats:
        lines.append(f"    {{ {name}, {count}, {stride:#x} }},")
    lines.append("};")
    out = ROOT / "src" / "gx" / "GxVertexFormats.inc"
    out.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{COUNT} formats -> {out}")


if __name__ == "__main__":
    main()
