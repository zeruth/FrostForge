"""Generates src/base/CharHangulTable.inc: the bitmap of the Hangul syllables the reference counts
as letters (FUN_142431360 reads it at 0x14295c590, a bit per syllable from U+AC00).

    python tools/gen_char_hangul.py
"""
from pathlib import Path

from wowbin import ROOT, Binary

b = Binary()
COUNT = (0x2ba4 + 63) // 64
words = [b.u32(0x14295c590 + i * 8) | (b.u32(0x14295c590 + i * 8 + 4) << 32) for i in range(COUNT)]

lines = ["// Generated by tools/gen_char_hangul.py from the reference's table; do not edit.", ""]
lines.append(f"const uint64_t s_hangulLetters[{COUNT}] = {{")
for i in range(0, COUNT, 4):
    lines.append("    " + ", ".join(f"0x{w:016x}ull" for w in words[i:i + 4]) + ",")
lines.append("};")
lines.append("")
path = Path(ROOT) / "src" / "base" / "CharHangulTable.inc"
path.write_text("\n".join(lines), newline="\n")
print(f"wrote {path} ({COUNT} words)")
