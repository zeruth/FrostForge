"""Reads the locale and region tables out of the binary into src/client/LocaleTables.hpp.

    python tools/gen_locale_tables.py

PTR_DAT_1426c43a0: the 12 locale codes by locale id ("enUS", ...; id 9 is empty).
DAT_1426c5440:     region names by region id, 256 entries, mostly empty.
PTR_1427b4cf0:     the 13 development portals and the region each stands for.
"""
from wowbin import ROOT, Binary


def c_string(s):
    return "nullptr" if s is None else '"' + s + '"'


def main() -> None:
    b = Binary()
    locales = []
    for i in range(12):
        p = b.u64(0x1426C43A0 + 8 * i)
        locales.append(b.cstr(p, 16) if p else None)
    regions = []
    for i in range(256):
        p = b.u64(0x1426C5440 + 8 * i)
        regions.append(b.cstr(p, 16) if p else None)
    portals = []
    for i in range(13):
        base = 0x1427B4CF0 + 16 * i
        portals.append((b.cstr(b.u64(base), 16), b.u32(base + 8)))

    out = ["// Generated by tools/gen_locale_tables.py from WowClassic-clean.exe. Do not edit.", "",
           "#ifndef CLIENT_LOCALE_TABLES_HPP", "#define CLIENT_LOCALE_TABLES_HPP", "", "#include <cstdint>", "",
           "// PTR_DAT_1426c43a0: locale codes by locale id", "static const char* const s_localeNames[12] = {"]
    out += [f"    {c_string(s)}," for s in locales]
    out += ["};", "", "// DAT_1426c5440: region names by region id", "static const char* const s_regionNames[256] = {"]
    for i in range(0, 256, 8):
        out.append("    " + " ".join(f"{c_string(s)}," for s in regions[i:i + 8]))
    out += ["};", "", "// PTR_1427b4cf0: development portals and their regions",
            "struct DEVPORTAL {", "    const char* m_name;", "    uint32_t m_region;", "};",
            "static const DEVPORTAL s_devPortals[13] = {"]
    out += [f"    {{ {c_string(n)}, {r} }}," for n, r in portals]
    out += ["};", "", "#endif", ""]
    (ROOT / "src" / "client" / "LocaleTables.hpp").write_text("\n".join(out))
    print("wrote src/client/LocaleTables.hpp")


if __name__ == "__main__":
    main()
