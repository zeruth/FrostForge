"""Generates src/base/CharSpaceTables.inc: the three-level table CharIsSpace
(FUN_142431460) reads -- a block per high byte (0x1429610b0), a row of sixteen per block and
nibble (0x142961060), and a flag per character in the row (0x142961020).

    python tools/gen_char_space.py
"""
from pathlib import Path

from wowbin import ROOT, Binary

b = Binary()


def byte(va: int) -> int:
    return b.u32(va) & 0xff


blocks = [byte(0x1429610b0 + i) for i in range(0x31)]
row_count = max(blocks) + 1
rows = [byte(0x142961060 + i) for i in range(row_count * 0x10)]
flag_count = max(rows) + 1
flags = [byte(0x142961020 + i) for i in range(flag_count * 0x10)]


def table(name: str, values: list[int]) -> str:
    lines = [f"const uint8_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), 16):
        lines.append("    " + ", ".join(f"0x{v:02x}" for v in values[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


out = ["// Generated by tools/gen_char_space.py from the reference's tables; do not edit.", ""]
out.append(table("s_spaceBlocks", blocks))
out.append("")
out.append(table("s_spaceRows", rows))
out.append("")
out.append(table("s_spaceFlags", flags))
out.append("")
path = Path(ROOT) / "src" / "base" / "CharSpaceTables.inc"
path.write_text("\n".join(out), encoding="utf-8", newline="\n")
print(path, row_count, flag_count)
