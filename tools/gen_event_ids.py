"""Reads the set of known event ids out of the binary into src/framescript/EventIds.hpp.

    python tools/gen_event_ids.py

FUN_140af6990 answers whether a 64-bit event id (the Murmur3 hash of the upper-cased event
name, FUN_1407bc5a0) is one the client knows: a compiled binary search over ~2k constants,
each tested with `cmp rcx, <id>` followed by `je`/`sete`. The ids it tests for equality are
the set; the range compares between them only steer the search.
"""
import capstone

from wowbin import ROOT, Binary

FUNC = 0x140AF6990
FUNC_SIZE = 21899  # its .pdata extent


def main() -> None:
    b = Binary()
    end = FUNC + FUNC_SIZE
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.detail = True
    code = b.image[b.off(FUNC):b.off(end)]
    insns = list(md.disasm(code, FUNC))
    regs = {}
    ids = set()
    at = {insn.address: n for n, insn in enumerate(insns)}
    for n, insn in enumerate(insns):
        ops = insn.operands
        if insn.mnemonic in ("movabs", "mov") and len(ops) == 2 and ops[0].type == capstone.x86.X86_OP_REG \
                and ops[1].type == capstone.x86.X86_OP_IMM:
            regs[ops[0].reg] = ops[1].imm & 0xFFFFFFFFFFFFFFFF
            # An id loaded just before a jump into a shared `cmp rcx, <reg>; sete` tail is
            # tested there, not here.
            following = insns[n + 1] if n + 1 < len(insns) else None
            if following is not None and following.mnemonic == "jmp" and following.operands[0].type == capstone.x86.X86_OP_IMM:
                target = at.get(following.operands[0].imm)
                if target is not None and target + 1 < len(insns):
                    tail = insns[target]
                    if tail.mnemonic == "cmp" and tail.op_str == f"rcx, {insn.reg_name(ops[0].reg)}" \
                            and insns[target + 1].mnemonic in ("je", "sete"):
                        ids.add(ops[1].imm & 0xFFFFFFFFFFFFFFFF)
            continue
        if insn.mnemonic != "cmp" or len(ops) != 2:
            continue
        if ops[0].type != capstone.x86.X86_OP_REG or insn.reg_name(ops[0].reg) != "rcx":
            continue
        if ops[1].type == capstone.x86.X86_OP_IMM:
            value = ops[1].imm & 0xFFFFFFFFFFFFFFFF
        elif ops[1].type == capstone.x86.X86_OP_REG and ops[1].reg in regs:
            value = regs[ops[1].reg]
        else:
            raise SystemExit(f"unexpected compare at {insn.address:#x}: {insn.op_str}")
        # (a pivot of the search is tested for equality too, after the branch that steers past it:
        # `cmp rcx, rax; ja <higher>; je <known>`. Only the next instruction was looked at, which
        # left out every pivot, about half the set: CURSOR_CHANGED, ACTIONBAR_UPDATE_USABLE and
        # the like were refused to every frame that registered them, 2026-10-21)
        if any(k < len(insns) and insns[k].mnemonic in ("je", "sete") for k in (n + 1, n + 2)):
            ids.add(value)
    ids = sorted(ids)
    out = ROOT / "src" / "framescript" / "EventIds.hpp"
    lines = [
        "#ifndef FRAMESCRIPT_EVENT_IDS_HPP",
        "#define FRAMESCRIPT_EVENT_IDS_HPP",
        "",
        "// Generated by tools/gen_event_ids.py from FUN_140af6990: every event id the client knows,",
        "// sorted. An event id is the Murmur3 hash of the upper-cased event name.",
        "",
        "#include <cstdint>",
        "",
        f"constexpr uint64_t EVENT_ID_COUNT = {len(ids)};",
        "",
        "inline constexpr uint64_t s_eventIds[EVENT_ID_COUNT] = {",
    ]
    for k in range(0, len(ids), 4):
        lines.append("    " + " ".join(f"0x{v:016x}ull," for v in ids[k:k + 4]))
    lines += ["};", "", "#endif", ""]
    out.write_text("\n".join(lines), newline="\n")
    print(f"{len(ids)} event ids -> {out}")


if __name__ == "__main__":
    main()
